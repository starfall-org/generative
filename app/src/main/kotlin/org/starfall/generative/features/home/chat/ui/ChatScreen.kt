        selectedModelName = backend.selectedModelName,
        onSendMessage = backend.onSendMessage,
        onSendMedia = backend.onSendMedia,
        onMediaModeChange = backend.onMediaModeChange,
        onStopGenerating = backend.onStopGenerating,
        onOpenDrawer = onOpenDrawer,
        onNewChat = onNewChat,
        onOpenTemporaryChat = onOpenTemporaryChat,
        onOpenSettings = onOpenSettings,
        featuresLogoImage = featuresLogoImage,
        workspaceLabel = backend.workspaceLabel,
        backgroundImage = backgroundImage,
        backgroundTransparency = backgroundTransparency,
        onRegenerate = backend.onRegenerate,
        onRetryFromError = backend.onRetryFromError,
        onEditMessage = backend.onEditMessage,
        onDeleteAssistantBlock = backend.onDeleteAssistantBlock,
        onDeleteMessage = backend.onDeleteMessage,
        onDeleteMessageVersion = backend.onDeleteMessageVersion,
        onSwitchVersion = backend.onSwitchVersion,
        onSelectModel = backend.onSelectModel,
        summaryProgress = backend.summaryProgress,
        onSetReasoningEffort = backend.onSetReasoningEffort,
        onSetThinkingPassback = backend.onSetThinkingPassback,
        onSetModelReasoningEffort = backend.onSetModelReasoningEffort,
