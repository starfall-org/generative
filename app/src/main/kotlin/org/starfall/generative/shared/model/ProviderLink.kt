package org.starfall.generative.shared.model

import android.net.Uri
import java.util.Locale
import java.util.UUID
import org.starfall.generative.shared.model.auth.AuthMethod
import org.starfall.generative.shared.model.auth.Authorization
import org.starfall.generative.shared.model.api.ModelApiType
import org.starfall.generative.shared.model.provider.ModelProvider

/** Import a new provider; query parameter `key` is the credential value, not a header name. */
fun parseProviderLink(uri: Uri): ModelProvider {
    require(uri.scheme?.lowercase(Locale.ROOT) in setOf("mg", "generative") &&
        uri.host.equals("provider", true) &&
        uri.path.orEmpty() in listOf("", "/")) { "Invalid provider link." }

    // `mg` is the canonical scheme and parameter names. Keep accepting the original
    // names so links generated by older app versions continue to work.
    fun option(name: String, legacyName: String?, default: String): String {
        val value = uri.getQueryParameter(name) ?: legacyName?.let(uri::getQueryParameter)
        return value?.trim()
            ?.takeIf { it.isNotEmpty() }
            ?.lowercase(Locale.ROOT)
            ?.replace('_', '-')
            ?: default
    }

    val type = when (option("provider_type", "type", "chat-completions")) {
        "chat-completions", "openai", "openai-chat-completions" -> ModelApiType.OPENAI
        "responses", "openai-responses" -> ModelApiType.OPENAI_RESPONSES
        "anthropic", "messages", "anthropic-messages" -> ModelApiType.ANTHROPIC
        "google", "gemini", "google-gemini" -> ModelApiType.GOOGLE
        "ollama" -> ModelApiType.OLLAMA
        "antigravity" -> ModelApiType.ANTIGRAVITY
        "github-copilot" -> ModelApiType.GITHUB_COPILOT
        "openai-codex" -> ModelApiType.OPENAI_CODEX
        "claude-code" -> ModelApiType.CLAUDE_CODE
        else -> throw IllegalArgumentException("Unsupported provider type in link.")
    }
    val method = when (option("auth_type", "auth", "platform")) {
        "platform", "platform-default" -> AuthMethod.PLATFORM_DEFAULT
        "none" -> AuthMethod.NONE
        "bearer", "bearer-token" -> AuthMethod.BEARER_TOKEN
        "query", "query-param" -> AuthMethod.QUERY_PARAM
        "header", "custom-header" -> AuthMethod.CUSTOM_HEADER
        "oauth", "oauth2" -> AuthMethod.OAUTH
        "other" -> AuthMethod.OTHER
        else -> throw IllegalArgumentException("Unsupported authentication method in link.")
    }
    val url = uri.getQueryParameter("url")?.trim()?.takeIf { it.isNotEmpty() } ?: type.defaultBaseUrl
    if (url.isNotEmpty()) {
        val parsed = Uri.parse(url)
        require(parsed.scheme?.lowercase(Locale.ROOT) in listOf("http", "https") && !parsed.host.isNullOrBlank()) {
            "Provider URL must be an HTTP or HTTPS address."
        }
    }
    val name = uri.getQueryParameter("name")?.trim()?.takeIf { it.isNotEmpty() }
        ?: type.defaultName.ifBlank { Uri.parse(url).host ?: "New provider" }
    val iconUrl = uri.getQueryParameter("icon_url")?.trim()?.takeIf { it.isNotEmpty() }
    if (iconUrl != null) {
        val parsed = Uri.parse(iconUrl)
        require(parsed.scheme?.lowercase(Locale.ROOT) in listOf("http", "https") && !parsed.host.isNullOrBlank()) {
            "Icon URL must be an HTTP or HTTPS address."
        }
    }
    val key = if (method in listOf(AuthMethod.NONE, AuthMethod.OAUTH)) "" else uri.getQueryParameter("key").orEmpty()
    // The ID is derived from the link's resolved contents, so delivering the same link again
    // (Activity recreation, a browser firing the intent twice) addresses the same provider
    // instead of creating a duplicate.
    val id = UUID.nameUUIDFromBytes(
        listOf(type.name, method.name, url, name, iconUrl.orEmpty(), key)
            .joinToString("\u0000").toByteArray(Charsets.UTF_8)
    ).toString()
    return ModelProvider(
        id = id,
        name = name,
        type = type,
        baseUrl = url,
        icon = iconUrl,
        auth = Authorization(
            method = method,
            key = when (method) {
                AuthMethod.BEARER_TOKEN, AuthMethod.CUSTOM_HEADER -> "Authorization"
                AuthMethod.QUERY_PARAM -> "key"
                else -> null
            },
            value = key
        )
    )
}
